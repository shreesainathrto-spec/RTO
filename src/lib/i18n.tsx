export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== "undefined") {
      const stored = localStorage.getItem("registry_language") as Language;
      if (stored === "en" || stored === "gu") {
        return stored;
      }
    }
    return "en";
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== "undefined") {
      localStorage.setItem("registry_language", lang);
      window.dispatchEvent(new Event("language-change"));
      // Force reload to completely clean and rebuild the React DOM
      window.location.reload();
    }
  };

  useEffect(() => {
    const handleLanguageChange = () => {
      if (typeof window !== "undefined") {
        const stored = localStorage.getItem("registry_language") as Language;
        if (stored && stored !== language) {
          setLanguageState(stored);
        }
      }
    };
    window.addEventListener("language-change", handleLanguageChange);
    return () => window.removeEventListener("language-change", handleLanguageChange);
  }, [language]);

  const t = (key: any, values?: Record<string, string | number>): string => {
    if (!key || typeof key !== "string") return String(key || "");
    const cleanKey = key.trim().toLowerCase();
    
    const activeLang: Language = language === "en" || language === "gu" ? language : "en";
    const dict = dictionaries[activeLang] || {};
    let translation = dict[cleanKey];

    // Split fallback translation for phrases / word-by-word parser
    if (!translation && activeLang === "gu") {
      const words = key.split(/(\s+)/);
      const translatedWords = words.map(word => {
        if (/^\s+$/.test(word)) return word;
        const cleanWord = word.trim().toLowerCase();
        
        // Match word ignoring common surrounding punctuation
        const match = cleanWord.match(/^([^a-z0-9]*)(.*?)([^a-z0-9]*)$/);
        if (match) {
          const prefix = match[1];
          const core = match[2];
          const suffix = match[3];
          const dictMatch = (dictionaries.gu || {})[core];
          if (dictMatch) {
            return prefix + dictMatch + suffix;
          }
        }
        return (dictionaries.gu || {})[cleanWord] || word;
      });
      translation = translatedWords.join("");
    }

    if (!translation) {
      translation = key;
    }

    // Handle interpolation if values are provided
    if (values) {
      Object.entries(values).forEach(([k, val]) => {
        translation = translation.replace(new RegExp(`{${k}}`, "gi"), String(val));
      });
    }

    // Dynamic text rule for numeric prefix/suffix like "7 TASKS" -> "7 ટાસ્ક"
    if (activeLang === "gu") {
      const match = key.match(/^(\d+)\s+(tasks|pending|completed|applications)$/i);
      if (match) {
        const num = match[1];
        const word = match[2].toLowerCase();
        const guWord = (dictionaries.gu || {})[word] || word;
        return `${num} ${guWord}`;
      }
    } else {
      const match = key.match(/^(\d+)\s+(tasks|pending|completed|applications)$/i);
      if (match) {
        return `${match[1]} ${match[2].toUpperCase()}`;
      }
      return translation.toUpperCase();
    }

    return activeLang === "gu" ? translation : translation.toUpperCase();
  };

  // Automated DOM translation engine when language is Gujarati
  useEffect(() => {
    if (language !== "gu") return;

    const translateNode = (node: Node) => {
      // 1. Handle text nodes
      if (node.nodeType === Node.TEXT_NODE) {
        const originalText = node.nodeValue || "";
        if (originalText.trim()) {
          // Check if this text node is already translated to avoid double translations
          const translatedText = t(originalText);
          if (translatedText !== originalText && node.nodeValue !== translatedText) {
            node.nodeValue = translatedText;
          }
        }
      }

      // 2. Handle input placeholders and button titles
      if (node.nodeType === Node.ELEMENT_NODE) {
        const element = node as HTMLElement;
        if (element.tagName === "INPUT" || element.tagName === "TEXTAREA") {
          const inputEl = element as HTMLInputElement | HTMLTextAreaElement;
          if (inputEl.placeholder) {
            const originalPlaceholder = inputEl.placeholder;
            const translatedPlaceholder = t(originalPlaceholder);
            if (translatedPlaceholder !== originalPlaceholder) {
              inputEl.placeholder = translatedPlaceholder;
            }
          }
        }
        if (element.title) {
          const originalTitle = element.title;
          const translatedTitle = t(originalTitle);
          if (translatedTitle !== originalTitle) {
            element.title = translatedTitle;
          }
        }
      }
    };

    // Recursive traversal function
    const translateTree = (rootNode: Node) => {
      // Skip scripts, styles, and iframe elements
      if (
        rootNode.nodeName === "SCRIPT" ||
        rootNode.nodeName === "STYLE" ||
        rootNode.nodeName === "IFRAME"
      ) {
        return;
      }
      translateNode(rootNode);
      rootNode.childNodes.forEach(translateTree);
    };

    // Initial translation run
    translateTree(document.body);

    // MutationObserver to translate new/updated nodes dynamically
    const observer = new MutationObserver((mutations) => {
      // Temporarily disconnect observer to prevent infinite trigger loops
      observer.disconnect();

      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          translateNode(mutation.target);
        } else if (mutation.type === "childList") {
          mutation.addedNodes.forEach(translateTree);
        }
      }

      observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
      });
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });

    return () => {
      observer.disconnect();
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
